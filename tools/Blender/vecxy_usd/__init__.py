def catalog_stamp():
    if not getattr(bpy.data,'filepath','') or not bpy.context.scene:return None
    path=schema.catalog_path(bpy.context)
    info=path.stat() if path.is_file() else None
    return str(path),info.st_mtime_ns if info else None,info.st_size if info else None

def watch_project_catalog():
    global _catalog_stamp
    try:
        stamp=catalog_stamp()
        if stamp!=_catalog_stamp:
            load_project_catalog(None)
            for window in bpy.context.window_manager.windows:
                for area in window.screen.areas:
                    if area.type=='VIEW_3D':area.tag_redraw()
    except Exception as error:print('Vecxy catalog watch:',error)
    return 1.0

@bpy.app.handlers.persistent
def load_project_catalog(dummy):
    global _catalog_stamp
    if getattr(bpy.data,'filepath',''):
        try:
            schema.reload_catalog(bpy.context)
            for owner in [*bpy.data.objects,*bpy.data.collections]:
                for component in owner.vecxy.components:schema.ensure_fields(component,overrides=isinstance(owner,bpy.types.Object) and bool(instance_collection(owner)))
            if bpy.context.scene.vecxy_usd.editing_proxy:bpy.ops.vecxy.finish_prototype()
        except Exception as error:print('Vecxy catalog:',error)
        _catalog_stamp=catalog_stamp()


